def list_territories() -> list[TerritoryProfile]:
    return [_PROFILES[tid] for tid in TERRITORY_IDS]


def get_territory(territory_id: str) -> TerritoryProfile:
    key = (territory_id or "").strip().lower()
    if key not in _PROFILES:
        known = ", ".join(TERRITORY_IDS)
        raise ValueError(f"Unknown territory {territory_id!r}; expected one of: {known}")
    return _PROFILES[key]


def resolve_territory_id(
    *,
    territory_id: str | None = None,
    env: os._Environ[str] | None = None,
) -> str:
    """Resolve territory from explicit id, CUSTOMER360_SEED_TERRITORY, or CUSTOMER360_TERRITORY."""
    if territory_id and str(territory_id).strip():
        return get_territory(str(territory_id)).id
    environ = env if env is not None else os.environ
    for key in ("CUSTOMER360_SEED_TERRITORY", "CUSTOMER360_TERRITORY"):
        raw = environ.get(key)
        if raw and str(raw).strip():
            return get_territory(str(raw)).id
    return DEFAULT_TERRITORY_ID
